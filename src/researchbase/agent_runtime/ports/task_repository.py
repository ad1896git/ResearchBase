"""Planning persistence port; no transport, credential or ORM handles cross it."""

from collections.abc import Callable
from types import TracebackType
from typing import Any, Protocol
from uuid import UUID

from researchbase.agent_runtime.application.contracts import CommandResult


class TaskRepository(Protocol):
    def lock_write(self, project: UUID, actor: UUID, command: UUID, task: UUID) -> None: ...
    def task(self, identity: UUID) -> dict[str, Any] | None: ...
    def steps(self, task: UUID) -> list[dict[str, Any]]: ...
    def edges(self, task: UUID) -> list[dict[str, Any]]: ...
    def inputs(self, task: UUID, *, step: bool = False) -> list[dict[str, Any]]: ...
    def receipt(self, project: UUID, actor: UUID, command: UUID) -> dict[str, Any] | None: ...
    def result(self, receipt: dict[str, Any], *, replayed: bool) -> CommandResult: ...
    def insert(self, table: str, row: dict[str, Any]) -> None: ...
    def update_task(self, identity: UUID, values: dict[str, Any]) -> None: ...
    def cancel_steps(self, task: UUID, at: Any) -> None: ...
    def authority(self, principal: Any, project: UUID) -> list[dict[str, Any]]: ...
    def at(self) -> Any: ...
    def project_active(self, project: UUID) -> bool: ...
    def input_version(self, kind: str, identity: UUID, project: UUID) -> dict[str, Any] | None: ...
    def events(self, task: UUID, *, step: bool = False) -> list[dict[str, Any]]: ...
    def force_constraints(self) -> None: ...


class TaskUnitOfWork(Protocol):
    @property
    def research_tasks(self) -> TaskRepository: ...

    def __enter__(self) -> Any: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc_value: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...
    def begin_research_task(self) -> None: ...
    def begin_formal_read(self) -> None: ...
    def commit(self) -> None: ...


TaskUowFactory = Callable[[], TaskUnitOfWork]


class UncertainTaskCommit(RuntimeError):
    """Internal signal to reconcile durable receipts without reexecuting a mutation."""
