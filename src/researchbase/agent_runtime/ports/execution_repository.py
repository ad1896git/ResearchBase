"""Intent persistence is accessible only through an Application UoW."""

from typing import Any, Protocol


class ExecutionRepository(Protocol):
    def lock_write(self, command, after_wait) -> None: ...
    def insert(self, table, row) -> dict[str, Any]: ...
    def receipt(self, command) -> dict[str, Any] | None: ...
    def execution(self, identity) -> dict[str, Any] | None: ...
    def inputs(self, task, step): ...
    def task(self, identity) -> dict[str, Any] | None: ...
    def steps(self, identity): ...
    def input_version(self, kind, identity, project): ...
    def force_constraints(self) -> None: ...
    def dto(self, row): ...
    def page(self, query): ...


class ExecutionUowFactory(Protocol):
    def __call__(self) -> Any: ...
