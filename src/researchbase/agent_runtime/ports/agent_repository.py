"""S1 transaction boundary; canonical state remains owned by ResearchBase."""

from datetime import datetime
from types import TracebackType
from typing import Any, Protocol

from researchbase.agent_runtime.application.agent_contracts import AgentCommandResult


class UncertainAgentCommit(RuntimeError):
    pass


class AgentRepository(Protocol):
    def lock_write(self, command) -> None: ...
    def authority(self, principal, project) -> list[dict[str, Any]]: ...
    def at(self) -> datetime: ...
    def project_active(self, project) -> bool: ...
    def human(self, actor) -> bool: ...
    def actor_exists(self, identity) -> bool: ...
    def receipt(self, command) -> dict[str, Any] | None: ...
    def version(self, identity) -> dict[str, Any] | None: ...
    def availability(self, identity) -> dict[str, Any] | None: ...
    def configuration(self, identity) -> dict[str, Any] | None: ...
    def live_agent(self, actor, project) -> bool: ...
    def insert(self, table, row) -> dict[str, Any]: ...
    def change(self, identity, status, revision, actor, at) -> None: ...
    def force_constraints(self) -> None: ...
    @staticmethod
    def result(receipt, *, replayed) -> AgentCommandResult: ...


class AgentUnitOfWork(Protocol):
    @property
    def agents(self) -> AgentRepository: ...

    phase2_identity: Any

    def __enter__(self) -> "AgentUnitOfWork": ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc_value: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...
    def begin_agent_command(self) -> None: ...
    def begin_formal_read(self) -> None: ...
    def commit(self) -> None: ...


class AgentUowFactory(Protocol):
    def __call__(self) -> AgentUnitOfWork: ...
