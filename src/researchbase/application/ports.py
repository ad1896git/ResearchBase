class UnitOfWork(Protocol):
    def enable_decision_error_normalization(self) -> None: ...

    @property
    def decision(self) -> Any: ...

    @property
    def scientific_conclusion(self) -> Any: ...

    @property
    def publication(self) -> Any: ...

    @property
    def internal_review(self) -> Any: ...

    @property
    def discussion(self) -> Any: ...

    @property
    def literature_evidence(self) -> Any: ...

    @property
    def metadata_observations(self) -> Any: ...

    actors: ActorRepository
    projects: ProjectRepository
    workspaces: WorkspaceRepository
    research_questions: ResearchQuestionRepository
    hypotheses: HypothesisRepository
    experiment_specs: ExperimentSpecRepository
    datasets: DatasetRepository
    dataset_snapshots: DatasetSnapshotRepository
    artifacts: ArtifactRepository
    artifact_versions: ArtifactVersionRepository
    metric_definitions: MetricDefinitionRepository
    metric_definition_versions: MetricDefinitionVersionRepository
    measurements: MeasurementRepository
    statistical_results: StatisticalResultRepository
    claims: ClaimRepository
    runs: RunRepository
    governance: GovernanceRepository
    phase2_identity: Phase2IdentityRepository

    @property
    def source_identity(self) -> SourceIdentityRepository: ...

    @property
    def source_merge(self) -> Any: ...

    @property
    def literature_search_execution(self) -> Any: ...

    @property
    def source_version(self) -> Any: ...

    @property
    def literature_search_plan(self) -> Any: ...

    def __enter__(self) -> UnitOfWork: ...

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc_value: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...

    def commit(self) -> None: ...

    def begin_serializable(self) -> None: ...

    def rollback(self) -> None: ...
