"""Stdlib offline documentation check. No DB/network/provisioning/runtime imports."""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def check(condition: bool, message: str) -> None:
    if not condition:
        raise SystemExit(message)


def main() -> None:
    check(sys.version_info[:2] == (3, 12), "Use an existing Python 3.12 interpreter")
    here = Path(__file__).resolve().parent
    manifest = json.loads((here / "portable-manifest.json").read_text(encoding="utf-8"))
    paths = set()
    for entry in manifest["payloads"]:
        name = entry["path"]
        check(type(name) is str and not Path(name).is_absolute(), "Relative paths required")
        check(all(p not in {"", ".", ".."} for p in name.split("/")), "Unsafe payload path")
        check(name not in paths, "Duplicate payload path")
        paths.add(name)
        file = here / name
        check(not file.is_symlink() and file.resolve().is_relative_to(here), "Symlink escape")
        raw = file.read_bytes()
        check(hashlib.sha256(raw).hexdigest() == entry["portable_sha256"], "Payload hash mismatch")
        if entry.get("byte_identical"):
            check(entry["original_sha256"] == entry["portable_sha256"], "Original hash mismatch")
    actual = {
        str(p.relative_to(here))
        for p in here.rglob("*")
        if p.is_file() and p.name != "portable-manifest.json"
    }
    check(paths == actual, "Unlisted/missing bundle payload")
    document = json.loads((here / "vectors.json").read_text(encoding="utf-8"))
    vectors = document["vectors"]
    check(len(vectors) == 55, "Expected 55 vectors")
    ids = set()
    for vector in vectors:
        name = vector["id"]
        check(
            type(name) is str and re.fullmatch("[A-Za-z0-9-]+", name) is not None,
            "Invalid vector id",
        )
        check(name not in ids, "Duplicate vector id")
        ids.add(name)
        check(vector["bytes_file"] == f"literal-bytes/{name}.bin", "Vector path mismatch")
        raw = (here / vector["bytes_file"]).read_bytes()
        check(len(raw) == vector["byte_length"], "Vector length mismatch")
        check(raw.hex() == vector["bytes_hex"], "Vector hex mismatch")
        check(hashlib.sha256(raw).hexdigest() == vector["sha256"], "Vector hash mismatch")
        check(
            raw.decode("utf8", errors="backslashreplace") == vector["literal_utf8"],
            "Vector UTF8 mismatch",
        )
    check(
        sum(v["expected"] == "ACCEPT_CODEC_ONLY" for v in vectors) == 7,
        "Expected seven codec accepts",
    )
    check(sum(v["expected"] == "REJECT" for v in vectors) == 48, "Expected 48 rejects")
    with tempfile.TemporaryDirectory(prefix="d01-doc-vectors-") as temporary:
        clone = Path(temporary)
        shutil.copyfile(here / "generate_vectors.py", clone / "generate_vectors.py")
        result = subprocess.run(
            [sys.executable, "-I", "-B", str(clone / "generate_vectors.py")],
            cwd=clone,
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
        check(result.returncode == 0, "Isolated specimen generation failed")
        check(
            (clone / "vectors.json").read_bytes() == (here / "vectors.json").read_bytes(),
            "Regenerated metadata differs",
        )
        generated = {p.name for p in (clone / "literal-bytes").glob("*.bin")}
        check(generated == {f"{name}.bin" for name in ids}, "Regenerated vector set differs")
        for name in generated:
            check(
                (clone / "literal-bytes" / name).read_bytes()
                == (here / "literal-bytes" / name).read_bytes(),
                "Regenerated bytes differ",
            )
    print("PASS_OFFLINE_SPECIMENS_ONLY: 55 exact vectors; 7 codec-only accepts / 48 rejects")
    notice = "NOT architecture freeze / D02 authority / PG or facility verification /"
    print(notice, "whole D01 completion")


if __name__ == "__main__":
    main()
